"""E2 师生对比表：DT / 专家规则 / BC。

A 部分（结果）：累计回报、剪枝比、刀数，及相对专家的差值 [95% bootstrap CI]、胜率、
               配对 Wilcoxon p、效应量（配对秩二列相关 r）
B 部分（决策画像）：单刀奖励及 R_q / R_i / R_c 分量、与专家剪除枝条集合的重合度（Jaccard）

读取 results/<stage>/<exp>/<split>/ 下的 eval_<tag>.csv 与 actions_<tag>.json，
输出到同目录：e2_table.tex（论文用，英文）、e2_table.md（中文预览）、
e2_table_preview.png（三线表样式图片预览，内容同 tex）。

用法（在 dt_pruning 目录下）：
    python ../experiments/scripts/e2_table.py --split val --exp e2_teacher
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import sys

import numpy as np
from scipy.stats import rankdata, wilcoxon

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "dt_pruning")))

from evaluate import result_dir  # noqa: E402

POLICIES = [("dt", "DT", "DT"), ("expert", "Expert rule (teacher)", "专家规则（老师）"),
            ("bc", "BC", "BC")]
REF = "expert"
N_BOOT = 10000


def load(d: str, tag: str):
    with open(os.path.join(d, f"eval_{tag}.csv"), encoding="utf-8") as f:
        rows = {r["tree"]: r for r in csv.DictReader(f)}
    with open(os.path.join(d, f"actions_{tag}.json"), encoding="utf-8") as f:
        traces = json.load(f)
    return rows, traces


def rank_biserial(diff: np.ndarray) -> float:
    d = diff[diff != 0]
    if d.size == 0:
        return 0.0
    r = rankdata(np.abs(d))
    return float((r[d > 0].sum() - r[d < 0].sum()) / r.sum())


def boot_ci(diff: np.ndarray, seed: int = 0) -> tuple[float, float]:
    rng = np.random.default_rng(seed)
    means = diff[rng.integers(0, diff.size, (N_BOOT, diff.size))].mean(axis=1)
    return float(np.quantile(means, 0.025)), float(np.quantile(means, 0.975))


def jaccard(ta: list, tb: list) -> float:
    sa = {x for c in ta for x in c["removed"]}
    sb = {x for c in tb for x in c["removed"]}
    return len(sa & sb) / max(len(sa | sb), 1)


def build(d: str) -> tuple[list[dict], int]:
    data = {tag: load(d, tag) for tag, _, _ in POLICIES}
    trees = sorted(set.intersection(*(set(rows) for rows, _ in data.values())))
    col = lambda tag, k: np.array([float(data[tag][0][t][k]) for t in trees])
    ref_ret = col(REF, "total_reward")
    out = []
    for tag, en, zh in POLICIES:
        rows, traces = data[tag]
        ret = col(tag, "total_reward")
        cuts = [c for t in trees for c in traces[t]]
        rec = {
            "tag": tag, "en": en, "zh": zh,
            "ret": (ret.mean(), ret.std(ddof=1)),
            "ratio": (col(tag, "final_pruning_ratio").mean(), col(tag, "final_pruning_ratio").std(ddof=1)),
            "cuts": (col(tag, "steps").mean(), col(tag, "steps").std(ddof=1)),
            "r_cut": np.mean([c["reward"] for c in cuts]),
            "rq": np.mean([c["rq"] for c in cuts]),
            "ri": np.mean([c["ri"] for c in cuts]),
            "rc": np.mean([c["rc"] for c in cuts]),
        }
        if tag != REF:
            diff = ret - ref_ret
            rec.update(
                diff=diff.mean(), ci=boot_ci(diff), win=float((diff > 0).mean()),
                p=float(wilcoxon(ret, ref_ret).pvalue), r=rank_biserial(diff),
                jac=float(np.mean([jaccard(traces[t], data[REF][1][t]) for t in trees])),
            )
        out.append(rec)
    return out, len(trees)


def fmt_p(p: float) -> str:
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def to_tex(recs: list[dict], n: int, split: str) -> str:
    split_en = "validation" if split == "val" else "test"
    lines = [
        "% auto-generated by experiments/scripts/e2_table.py",
        r"\begin{table}[H]",
        r"\centering",
        rf"\caption{{Teacher--student comparison on {n} unseen {split_en} trees: DT versus the expert rule that generated its training data, with single-step behaviour cloning (BC) as the pure-imitation reference}}",
        r"\label{tab:teacher_student}",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{lcccccc}",
        r"\toprule",
        r"\multicolumn{7}{l}{\textit{(a) Pruning outcome}} \\",
        r"\textbf{Policy} & \textbf{Return} & \textbf{Pruning ratio} & \textbf{Cuts} & "
        r"\textbf{$\Delta$Return [95\% CI]} & \textbf{Win} & \textbf{$p$ ($r$)} \\",
        r"\midrule",
    ]
    for x in recs:
        if x["tag"] == REF:
            tail = r"-- & -- & --"
        else:
            tail = (rf"{x['diff']:+.1f} [{x['ci'][0]:+.1f}, {x['ci'][1]:+.1f}] & "
                    rf"{100 * x['win']:.1f}\% & {fmt_p(x['p'])} ({x['r']:+.2f})")
        lines.append(rf"{x['en']} & {x['ret'][0]:.1f} $\pm$ {x['ret'][1]:.1f} & "
                     rf"{x['ratio'][0]:.3f} $\pm$ {x['ratio'][1]:.3f} & "
                     rf"{x['cuts'][0]:.1f} $\pm$ {x['cuts'][1]:.1f} & {tail} \\")
    lines += [
        r"\midrule",
        r"\multicolumn{7}{l}{\textit{(b) Per-cut decision profile}} \\",
        r"\textbf{Policy} & \textbf{Reward / cut} & \textbf{$R_q$ / cut} & \textbf{$R_i$ / cut} & "
        r"\textbf{$R_c$ / cut} & \multicolumn{2}{c}{\textbf{Overlap (Jaccard)}} \\",
        r"\midrule",
    ]
    for x in recs:
        jac = "--" if x["tag"] == REF else f"{x['jac']:.3f}"
        lines.append(rf"{x['en']} & {x['r_cut']:.2f} & {x['rq']:.2f} & {x['ri']:.2f} & "
                     rf"{x['rc']:.3f} & \multicolumn{{2}}{{c}}{{{jac}}} \\")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\vspace{2pt}",
        r"\footnotesize Note: values are mean $\pm$ s.d. over trees. $\Delta$Return is paired against the expert rule on the same tree and Win is the share of trees with a higher return than the expert; "
        r"95\% CI from 10\,000 bootstrap resamples; $p$ from the paired Wilcoxon signed-rank test, $r$ is the matched-pairs rank-biserial correlation. "
        r"Per-cut values are averaged over all cuts; $R_q$, $R_i$, $R_c$ are the unweighted branch-quality, state-improvement and constraint terms of the composite reward. "
        r"Overlap is the Jaccard index between the sets of branches removed from the same tree by the policy and by the expert, including descendants removed with a cut.",
        r"\end{table}",
        "",
    ]
    return "\n".join(lines)


def to_md(recs: list[dict], n: int, split: str) -> str:
    split_zh = "验证树" if split == "val" else "测试树"
    L = [f"# E2 师生对比表（{n} 棵{split_zh}，预览）", "",
         "**(a) 剪枝结果**", "",
         "| 策略 | 累计回报 | 剪枝比 | 刀数 | 相对专家回报差 [95% CI] | 胜率 | p（效应量 r） |",
         "|---|---|---|---|---|---|---|"]
    for x in recs:
        tail = ("— | — | —" if x["tag"] == REF else
                f"{x['diff']:+.1f} [{x['ci'][0]:+.1f}, {x['ci'][1]:+.1f}] | {100 * x['win']:.1f}% | "
                f"{fmt_p(x['p'])}（{x['r']:+.2f}）")
        L.append(f"| {x['zh']} | {x['ret'][0]:.1f} ± {x['ret'][1]:.1f} | "
                 f"{x['ratio'][0]:.3f} ± {x['ratio'][1]:.3f} | {x['cuts'][0]:.1f} ± {x['cuts'][1]:.1f} | {tail} |")
    L += ["", "**(b) 单刀决策画像**", "",
          "| 策略 | 单刀奖励 | R_q / 刀 | R_i / 刀 | R_c / 刀 | 与专家剪除集合重合度 |",
          "|---|---|---|---|---|---|"]
    for x in recs:
        jac = "—" if x["tag"] == REF else f"{x['jac']:.3f}"
        L.append(f"| {x['zh']} | {x['r_cut']:.2f} | {x['rq']:.2f} | {x['ri']:.2f} | {x['rc']:.3f} | {jac} |")
    L += ["", "注：均值 ± 标准差（按树）；回报差为同一棵树上与专家配对相减，95% CI 为 10000 次 bootstrap；"
          "p 为配对 Wilcoxon 符号秩检验，r 为配对秩二列相关；单刀值对全部刀取平均，R_q / R_i / R_c 为未加权的"
          "枝条质量、状态改善、约束分量；重合度为两者从同一棵树剪除枝条集合（含连带剪除的子枝）的 Jaccard 系数。", ""]
    return "\n".join(L)


def to_png(recs: list[dict], n: int, split: str, path: str):
    """三线表样式预览图（内容同 e2_table.tex），用于未装 LaTeX 时查看。"""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.family": "Times New Roman", "mathtext.fontset": "stix"})

    split_en = "validation" if split == "val" else "test"
    pm = "\u00b1"
    a_head = ["Policy", "Return", "Pruning ratio", "Cuts", r"$\Delta$Return [95% CI]", "Win", "$p$ ($r$)"]
    a_rows = []
    for x in recs:
        tail = (["\u2013"] * 3 if x["tag"] == REF else
                [f"{x['diff']:+.1f} [{x['ci'][0]:+.1f}, {x['ci'][1]:+.1f}]",
                 f"{100 * x['win']:.1f}%", f"{fmt_p(x['p'])} ({x['r']:+.2f})"])
        a_rows.append([x["en"], f"{x['ret'][0]:.1f} {pm} {x['ret'][1]:.1f}",
                       f"{x['ratio'][0]:.3f} {pm} {x['ratio'][1]:.3f}",
                       f"{x['cuts'][0]:.1f} {pm} {x['cuts'][1]:.1f}", *tail])
    b_head = ["Policy", "Reward / cut", "$R_q$ / cut", "$R_i$ / cut", "$R_c$ / cut", "Overlap (Jaccard)"]
    b_rows = [[x["en"], f"{x['r_cut']:.2f}", f"{x['rq']:.2f}", f"{x['ri']:.2f}", f"{x['rc']:.3f}",
               "\u2013" if x["tag"] == REF else f"{x['jac']:.3f}"] for x in recs]

    widths = [1.75, 1.15, 1.05, 0.85, 1.75, 0.6, 1.05]
    xs_a = np.concatenate([[0], np.cumsum(widths)])
    W, lh = xs_a[-1], 0.26
    xs_b = np.concatenate([[0], widths[0] + np.arange(6) * (W - widths[0]) / 5])
    lines_y = 2 + 2 * (1 + 1 + len(recs)) + 1
    fig, ax = plt.subplots(figsize=(W + 0.2, lh * (lines_y + 4.2)))
    ax.set_xlim(-0.1, W + 0.1)
    ax.set_ylim(-lh * 4.2, lh * lines_y)
    ax.axis("off")

    y = lh * lines_y
    ax.text(W / 2, y - lh * 0.5,
            f"Table X. Teacher\u2013student comparison on {n} unseen {split_en} trees",
            ha="center", va="center", fontsize=10)
    y -= lh * 1.3
    ax.hlines(y, 0, W, lw=1.2, color="k")

    def row(cells, y, xs, bold=False):
        for i, c in enumerate(cells):
            cx = xs[i] + 0.05 if i == 0 else (xs[i] + xs[i + 1]) / 2
            ax.text(cx, y, c, ha="left" if i == 0 else "center", va="center", fontsize=9,
                    fontweight="bold" if bold else "normal")

    for title, head, rows, xs in (("(a) Pruning outcome", a_head, a_rows, xs_a),
                                  ("(b) Per-cut decision profile", b_head, b_rows, xs_b)):
        y -= lh
        ax.text(0.05, y, title, ha="left", va="center", fontsize=9, style="italic")
        y -= lh
        row(head, y, xs, bold=True)
        y -= lh * 0.55
        ax.hlines(y, 0, W, lw=0.6, color="k")
        for r in rows:
            y -= lh
            row(r, y, xs)
        y -= lh * 0.55
        ax.hlines(y, 0, W, lw=1.2 if title.startswith("(b)") else 0.6, color="k")

    note = ("Note: mean \u00b1 s.d. over trees. \u0394Return is paired against the expert rule on the same tree; "
            "Win = share of trees with a higher return than the expert;\n95% CI from 10,000 bootstrap resamples; "
            "p from the paired Wilcoxon signed-rank test, r = matched-pairs rank-biserial correlation. "
            "Per-cut values are averaged over all cuts;\nRq, Ri, Rc are the unweighted branch-quality, "
            "state-improvement and constraint terms. Overlap = Jaccard index of the branch sets removed from "
            "the same tree\nby the policy and by the expert, including descendants removed with a cut.")
    ax.text(0, y - lh * 0.4, note, ha="left", va="top", fontsize=7.5, linespacing=1.5)
    fig.savefig(path, dpi=200, bbox_inches="tight", facecolor="white")
    plt.close(fig)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", choices=["val", "test"], default="val")
    ap.add_argument("--stage", choices=["dev", "paper"], default="dev")
    ap.add_argument("--exp", required=True)
    args = ap.parse_args()

    d = result_dir(args.stage, args.exp, args.split)
    recs, n = build(d)
    for name, text in (("e2_table.tex", to_tex(recs, n, args.split)),
                       ("e2_table.md", to_md(recs, n, args.split))):
        with open(os.path.join(d, name), "w", encoding="utf-8") as f:
            f.write(text)
        print("已保存:", os.path.join(d, name))
    png = os.path.join(d, "e2_table_preview.png")
    to_png(recs, n, args.split, png)
    print("已保存:", png)


if __name__ == "__main__":
    main()
